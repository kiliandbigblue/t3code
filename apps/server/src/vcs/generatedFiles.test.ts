import { describe, expect, it } from "vite-plus/test";

import {
  parseGeneratedHeaderMatches,
  parseLinguistGenerated,
  selectGeneratedPaths,
} from "./generatedFiles.ts";

describe("generated file detection", () => {
  it("lets linguist-generated override headers and file names", () => {
    const attributes = parseLinguistGenerated(
      [
        "proto/gen/index.ts\0linguist-generated\0set",
        "keep.pb.go\0linguist-generated\0unset",
        "docs/api.md\0linguist-generated\0true",
        "pnpm-lock.yaml\0linguist-generated\0false",
        "src/app.ts\0linguist-generated\0unspecified",
        "",
      ].join("\0"),
    );
    const headers = new Set(["keep.pb.go", "store/store.go"]);
    expect(
      selectGeneratedPaths(
        [
          "proto/gen/index.ts",
          "keep.pb.go",
          "docs/api.md",
          "pnpm-lock.yaml",
          "src/app.ts",
          "store/store.go",
          "yarn.lock",
        ],
        attributes,
        headers,
      ),
    ).toEqual(["proto/gen/index.ts", "docs/api.md", "store/store.go", "yarn.lock"]);
  });

  it("only counts markers near the top of the file", () => {
    const stdout = [
      "HEAD:store/store.go\x001\0generated by protoc-gen-storev2. DO NOT EDIT",
      "HEAD:weird:name.ts\x002\0@generated",
      "HEAD:src/notes.ts\x0040\0@generated",
      "",
    ].join("\n");
    expect([...parseGeneratedHeaderMatches(stdout, "HEAD")]).toEqual([
      "store/store.go",
      "weird:name.ts",
    ]);
    expect([...parseGeneratedHeaderMatches("new.ts\x001\0@generated\n", null)]).toEqual(["new.ts"]);
  });
});
